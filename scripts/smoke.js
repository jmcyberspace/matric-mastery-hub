import assert from 'node:assert/strict';
const origin = process.argv[2] || 'http://127.0.0.1:3010';
const get = path => fetch(new URL(path, origin), { signal: AbortSignal.timeout(10000), redirect: 'error' });
const health = await get('/healthz');
assert.equal(health.status, 200); assert.equal((await health.json()).status, 'ok');
const session = await get('/api/auth/session');
assert.equal(session.status, 200); assert.equal((await session.json()).user, null);
assert.equal(session.headers.get('cache-control'), 'no-store');
assert.match(session.headers.get('content-security-policy'), /frame-ancestors 'none'/);
assert.match(session.headers.get('strict-transport-security'), /max-age=31536000/);
assert.equal((await get('/api/overview')).status, 401);
const page = await get('/login');
assert.equal(page.status, 200);
const html = await page.text();
assert.match(html, /<title>Matric Mastery/);
const asset = html.match(/src="(\/assets\/[^\"]+\.js)"/);
assert.ok(asset, 'Built entry script must be present');
assert.equal((await get(asset[1])).status, 200);
console.log('HTTP smoke check passed: database, anonymous access boundaries, security headers, page and built assets.');
